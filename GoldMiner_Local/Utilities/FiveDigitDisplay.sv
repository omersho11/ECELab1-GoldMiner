module FiveDigitDisplay #(
	parameter logic [7:0] color = 8'hff
) (	
	input	logic	clk,
	input	logic	resetN,
	input logic enable,
	input logic	[10:0] topLeftX,
	input logic	[10:0] topLeftY,
	input logic	[10:0] pixelX,
	input logic	[10:0] pixelY,
	input logic [4:0] [3:0] digits,

	output logic drawingRequest
);

localparam DISPLAY_WIDTH = 80; // 5 * 16;
localparam DISPLAY_HEIGHT = 32;
localparam DIGIT_WIDTH = 16;
localparam DIGIT_HEIGHT = 32;

logic	[10:0] offsetX;
logic	[10:0] offsetY;
logic insideRectangle;

(* ramstyle = "M10K" *) logic [15:0] fontRows [0:383];
initial  $readmemh("Assets/digits.hex", fontRows);


square_object #(
	.OBJECT_WIDTH_X(DISPLAY_WIDTH),
	.OBJECT_HEIGHT_Y(DISPLAY_HEIGHT)
) timeDisplaySquareObject (
	.clk(clk),
   .resetN(resetN),
	.pixelX(pixelX),
	.pixelY(pixelY),
	.topLeftX(topLeftX),
	.topLeftY(topLeftY),
	
	.offsetX(offsetX),
	.offsetY(offsetY),
	.drawingRequest(insideRectangle),
	.RGBout(8'b0)
);






																	
	


// pipeline (ff) to get the pixel color from the array

logic [2:0] currentDigit;
assign currentDigit = offsetX >> 4;
logic [3:0] localOffsetX;
assign localOffsetX = offsetX[3:0]; // % 16

logic [10:0] address;
logic [15:0] dataRow;
logic [3:0] localOffsetX_r;
logic insideRectangle_r;
logic enable_r;

always_comb begin
	address = digits[currentDigit] * DIGIT_HEIGHT + offsetY;
end

always_ff @(posedge clk) begin
  dataRow <= fontRows[address];
end


always_ff @(posedge clk or negedge resetN) begin
  if (!resetN) begin
    localOffsetX_r <= 0;
    insideRectangle_r <= 0;
    enable_r <= 0;
  end else begin
    localOffsetX_r <= localOffsetX;
    insideRectangle_r <= insideRectangle;
    enable_r <= enable;
  end
end


always_ff @(posedge clk or negedge resetN) begin
  if(!resetN) drawingRequest <= 1'b0;
  else drawingRequest <= (enable_r && insideRectangle_r) ? dataRow[15-localOffsetX_r] : 1'b0;
end

